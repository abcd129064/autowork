def _hex_to_rgb(hex_color: str):
    h = hex_color.lstrip("#")
    if len(h) == 3:
        h = "".join(ch * 2 for ch in h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def _rgb_to_hex(rgb):
    return "#" + "".join(f"{max(0, min(255, int(round(c)))):02x}" for c in rgb)


def lighten(hex_color: str, pct: float) -> str:
    """按百分比提亮（向白混合）。hover 态一般 +10~15%。"""
    r, g, b = _hex_to_rgb(hex_color)
    return _rgb_to_hex(tuple(c + (255 - c) * pct for c in (r, g, b)))


def darken(hex_color: str, pct: float) -> str:
    """按百分比压暗（向黑混合）。pressed 态一般 -15~20%。"""
    r, g, b = _hex_to_rgb(hex_color)
    return _rgb_to_hex(tuple(c * (1 - pct) for c in (r, g, b)))

